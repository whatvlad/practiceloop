// Public shapes the UI works with. None of them carries an expected answer,
// a solution or generator data: those arrive only from the reveal calls.
import type { VisualSpec } from '../visual/spec';

/** ADR-005: practice has two areas, and every topic belongs to exactly one. */
export type AreaSlug = 'algebra' | 'mathematical-analysis' | 'probability-statistics';

export interface LegacyAnswerInputSpec {
  kind: 'boolean' | 'finite_set' | 'interval';
  maxBytes: 256;
  maxItems?: 8;
}

export interface ComputationalInputSpec {
  kind: 'real_set' | 'tuple' | 'category' | 'formula' | 'limit_result';
  maxBytes: 256;
  maxItems?: 8;
  symbols?: Record<string, 'real' | 'positive' | 'integer'>;
  components?: ComputationalInputSpec[];
  labels?: string[];
  choices?: string[];
}

export type AnswerInputSpec = LegacyAnswerInputSpec | ComputationalInputSpec;

/** A topic's slug. The list of topics comes from GET /topics (#191), not from this build. */
export type TopicSlug = string;

/** A topic, or mixed practice: the server draws a topic of one area with fixed, published weights (#36). */
export type PracticeTopic = TopicSlug | 'mixed';

/** ADR-007 decision 4: how many distinct problems a worksheet group can get at each level. */
export type WorksheetCapacity = Partial<Record<Difficulty, number>>;

export interface MixedPractice {
  availableDifficulties: Difficulty[];
  weights: Partial<Record<TopicSlug, number>>;
  worksheetCapacity?: WorksheetCapacity;
}

export interface Area {
  slug: AreaSlug;
  name: string;
}

export interface AvailableArea extends Area {
  /** Null when the area has fewer than two topics, and for guests, who have only the fixed demo. */
  mixed: MixedPractice | null;
}

export interface Catalogue {
  /** Only the areas that offer a topic, in the server's order. */
  areas: AvailableArea[];
  topics: AvailableTopic[];
}

export interface Topic {
  slug: TopicSlug;
  name: string;
  area: AreaSlug;
}

export interface AvailableTopic extends Topic {
  availableDifficulties: Difficulty[];
  worksheetCapacity?: WorksheetCapacity;
}

export type Difficulty = 1 | 2 | 3 | 4 | 5;

/** Three API outcomes plus a display state for the missing_constant feedback code. */
export type CheckResult = 'correct' | 'incorrect' | 'invalid' | 'missing_constant';

/** A declared mistake the checker matched unambiguously (#36); null means a general hint. */
export const FEEDBACK_CODES = [
  'power_rule', 'trig_sign', 'chain_factor', 'log_absolute', 'split_product', 'parts_sign',
  'cycle_factor', 'partial_fraction_sign', 'definite_not_evaluated', 'bounds_reversed', 'definite_constant',
  'derivative_power', 'derivative_trig_sign', 'derivative_chain', 'derivative_factors', 'quotient_sign',
  'derivative_constant', 'missing_jacobian', 'z_bounds',
  'partial_held_constant', 'partial_chain_term', 'jacobian_missing_r', 'jacobian_sign',
] as const;
export type FeedbackCode = (typeof FEEDBACK_CODES)[number];

export interface CheckOutcome {
  result: CheckResult;
  feedback: FeedbackCode | null;
}

/** Saved practice records invalid expressions too; preview does not. */
export type AttemptResult = CheckResult | null;

export interface PublicProblem {
  answerInput?: AnswerInputSpec;
  attemptCount?: number;
  saved?: boolean;
  id: string;
  topic: TopicSlug;
  difficulty: Difficulty;
  problemLatex: string;
  createdAt: string;
  answerRevealed: boolean;
  solutionRevealed: boolean;
  lastResult: AttemptResult;
  lastFeedback?: FeedbackCode | null;
  /** Generated by mixed practice in this session, so the next problem is mixed too. */
  mixed?: boolean;
  lastAnswer: string | null;
  /** The worksheet that created this problem (ADR-007), or null. */
  worksheetId?: string | null;
}

export interface RevealedAnswer {
  answerLatex: string;
}

export interface SolutionStep {
  say: string;
  latex: string;
}

export interface RevealedSolution {
  steps: SolutionStep[];
  /** ADR-006: an interactive picture of the solution, when this build understands it. */
  visual?: VisualSpec;
}

/** Only the active reopened card receives previously authorized reveal payloads. */
export interface OpenedProblem {
  problem: PublicProblem;
  answer?: RevealedAnswer;
  solution?: RevealedSolution;
  /** The owner's live share (#37), if any. */
  share?: ProblemShare | null;
}

/** An owner's live share: the link token, the short code and when both stop working. */
export interface ProblemShare {
  token: string;
  code: string;
  expiresAt: string;
}

/** All a shared link or code reveals: never answers, results, solutions or the owner. */
export interface SharedProblem {
  answerInput?: AnswerInputSpec;
  topic: TopicSlug;
  difficulty: Difficulty;
  problemLatex: string;
}

export type ShareUnavailable = 'invalid' | 'not_found' | 'expired' | 'revoked';

export interface ProblemPage {
  items: PublicProblem[];
  nextCursor: string | null;
}

export interface Account {
  id: string;
  name: string;
  email: string;
  provider: 'Google';
}

export interface ProfileCounts {
  generated: number;
  attempted: number;
  correct: number;
}

export interface OmissionMetric {
  checkedAttempts: number;
  omitted: number;
  rate: number | null;
}

export interface LearningStatistics extends OmissionMetric {
  byTopicDifficulty: (OmissionMetric & { topic: TopicSlug; difficulty: Difficulty })[];
  weekly: (OmissionMetric & { week: string })[];
}

/** Problem report categories (#38), as app.api.reports accepts them. */
export const REPORT_CATEGORIES = ['answer_check', 'solution', 'statement', 'display', 'other'] as const;
export type ReportCategory = (typeof REPORT_CATEGORIES)[number];
