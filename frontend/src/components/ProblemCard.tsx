import type { CheckResult, Difficulty, FeedbackCode, SolutionStep, TopicSlug } from '../data/types';
import { answerVariables, keypadVariables, leadText, problemKind, type ProblemKind } from '../format';
import { problemTag } from '../data/topics';
import { AnswerInput } from './AnswerInput';
import { Button } from './Button';
import { DifficultyDots } from './DifficultyScale';
import { ResultBanner, RevealedAnswer } from './ResultBanner';
import { SolutionSteps } from './SolutionSteps';
import { SolutionVisual } from '../visual/SolutionVisual';
import type { VisualSpec } from '../visual/spec';
import { Tex } from './Tex';
import text from '../../../backend/app/content/en.json';

interface ProblemCardProps {
  topic: TopicSlug;
  difficulty: Difficulty;
  problemLatex: string;
  /** Generated by mixed practice: the tag names the drawn topic and the mode. */
  mixed?: boolean;
  /** Eyebrow at the top right, e.g. "Saved to history". */
  headLabel?: string;
  answer: string;
  onAnswerChange: (value: string) => void;
  result: CheckResult | null;
  /** A declared mistake the incorrect answer matched; otherwise a general hint shows. */
  feedback?: FeedbackCode | null;
  /** A request is in flight; buttons wait for it. */
  busy?: boolean;
  onCheck: () => void;
  onShowAnswer: () => void;
  onShowSolution: () => void;
  onNext: () => void;
  nextLabel?: string;
  /** Present only after the backend returns it for Show Answer. */
  answerLatex?: string | null;
  /** Present only after the backend returns it for Show Solution. */
  solution?: readonly SolutionStep[] | null;
  /** The solution's interactive picture (ADR-006), shown under the steps. */
  visual?: VisualSpec | null;
}

/** Targeted feedback only for a matched mistake (#36); otherwise a general hint, never a guess. */
export function incorrectMessage(feedback: FeedbackCode | null, kind: ProblemKind): string {
  if (feedback) return text[`feedback_${feedback}`];
  return { indefinite: text.general_hint, definite: text.general_hint_definite, double: text.general_hint_multiple,
    triple: text.general_hint_multiple, derivative: text.general_hint_derivative, partial: text.general_hint_derivative,
    numeric: 'Check your calculation, or reveal the solution.', expression: 'Check your work, or reveal the solution.' }[kind];
}

const PLACEHOLDERS: Record<ProblemKind, string> = {
  indefinite: 'e.g. x^2/2 + C',
  definite: 'e.g. 3/2 or e - 1',
  double: 'e.g. 8pi or (e - 1)/2',
  triple: 'e.g. 8pi/3 or 1/6',
  derivative: 'e.g. 2x cos(x^2)',
  partial: 'e.g. 2xy or r^2 cos(2θ)',
  numeric: 'e.g. 3/2',
  expression: 'e.g. 2x + 1',
};

/** The one lifted surface: a problem, its answer field and every action on it. */
export function ProblemCard({
  topic,
  difficulty,
  problemLatex,
  mixed = false,
  headLabel,
  answer,
  onAnswerChange,
  result,
  feedback = null,
  busy = false,
  onCheck,
  onShowAnswer,
  onShowSolution,
  onNext,
  nextLabel = 'Generate next problem',
  answerLatex,
  solution,
  visual,
}: ProblemCardProps) {
  const solved = result === 'correct';
  const kind = problemKind(topic, problemLatex);
  const message = result === 'incorrect' ? incorrectMessage(feedback, kind) : undefined;
  return (
    <section className="pl-problem" aria-label="Problem" aria-busy={busy}>
      <div className="pl-problem-head">
        <div className="meta">
          <span className="pl-tag">{problemTag(topic)}{mixed && ' · Mixed practice'}</span>
          <span className="pl-small pl-muted">
            <DifficultyDots level={difficulty} />
          </span>
        </div>
        {headLabel && <span className="pl-label">{headLabel}</span>}
      </div>
      <div className="pl-stack pl-gap-3">
        <p className="pl-lead">{leadText(kind)}</p>
        <div className="pl-expr">
          <Tex latex={problemLatex} display />
        </div>
      </div>
      <AnswerInput
        id="answer"
        value={answer}
        onChange={onAnswerChange}
        state={result}
        placeholder={PLACEHOLDERS[kind]}
        describedBy={result ? 'answer-result' : undefined}
        onEnter={solved || busy ? undefined : onCheck}
        assist
        variables={answerVariables(kind, problemLatex)}
        keypadVariables={keypadVariables(kind, problemLatex, topic)}
        hint={
          <>
            Type <code>/</code> for a fraction, <code>^</code> for a power, <code>sqrt</code> for a root, or use the keys. Press Enter to check.
          </>
        }
      />
      <div className="pl-result-slot" role="status">{result && <ResultBanner id="answer-result" state={result} message={message} live={false} />}</div>
      {busy && <p role="status" className="pl-small pl-muted">Working…</p>}
      <Button size="lg" block onClick={onCheck} disabled={solved || busy}>
        Check answer
      </Button>
      <div className="pl-actions">
        <Button variant="secondary" onClick={onShowAnswer} disabled={busy}>
          Show answer
        </Button>
        <Button variant="secondary" onClick={onShowSolution} disabled={busy}>
          Show solution
        </Button>
        <span className="pl-spacer" />
        <Button variant={solved ? 'primary' : 'ghost'} arrow onClick={onNext} disabled={busy}>
          {nextLabel}
        </Button>
      </div>
      {answerLatex && <RevealedAnswer latex={answerLatex} />}
      {solution && <SolutionSteps steps={solution} />}
      {solution && visual && <SolutionVisual spec={visual} />}
    </section>
  );
}
